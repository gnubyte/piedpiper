//! Compiles shaders/*.comp to SPIR-V with glslc and writes `consts.glsl` with the exact bit
//! patterns of the core's f32 constants (taken from Rust literals here, so GLSL's own decimal
//! parsing can never round one differently).
//!
//! glslc comes from the Vulkan SDK or the Android NDK (`shader-tools/<host>/glslc`). Set
//! GLSLC to its path if it is not found automatically.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn find_glslc() -> PathBuf {
    if let Some(p) = env::var_os("GLSLC") {
        return PathBuf::from(p);
    }
    let exe = if cfg!(windows) { "glslc.exe" } else { "glslc" };
    if let Some(sdk) = env::var_os("VULKAN_SDK") {
        let p = Path::new(&sdk).join("Bin").join(exe);
        if p.exists() {
            return p;
        }
        let p = Path::new(&sdk).join("bin").join(exe);
        if p.exists() {
            return p;
        }
    }
    let mut sdks: Vec<PathBuf> = Vec::new();
    for var in ["ANDROID_NDK_HOME", "ANDROID_NDK_ROOT"] {
        if let Some(v) = env::var_os(var) {
            sdks.push(PathBuf::from(v));
        }
    }
    for var in ["ANDROID_HOME", "ANDROID_SDK_ROOT"] {
        if let Some(v) = env::var_os(var) {
            sdks.push(PathBuf::from(v).join("ndk"));
        }
    }
    if let Some(local) = env::var_os("LOCALAPPDATA") {
        sdks.push(PathBuf::from(local).join("Android").join("Sdk").join("ndk"));
    }
    if let Some(home) = env::var_os("HOME") {
        sdks.push(PathBuf::from(&home).join("Android").join("Sdk").join("ndk"));
        sdks.push(PathBuf::from(&home).join("Library").join("Android").join("sdk").join("ndk"));
    }
    for base in sdks {
        // Either an NDK itself or a folder of versioned NDKs.
        let mut roots = vec![base.clone()];
        if let Ok(rd) = fs::read_dir(&base) {
            let mut v: Vec<PathBuf> = rd.flatten().map(|e| e.path()).collect();
            v.sort();
            v.reverse();
            roots.extend(v);
        }
        for r in roots {
            let tools = r.join("shader-tools");
            if let Ok(rd) = fs::read_dir(&tools) {
                for host in rd.flatten() {
                    let p = host.path().join(exe);
                    if p.exists() {
                        return p;
                    }
                }
            }
        }
    }
    PathBuf::from(exe) // hope it is on PATH
}

fn consts_glsl() -> String {
    // (name, value) — the values are the core's literals, spelled exactly as in
    // crates/core/src/fpmath.rs, model.rs and simd.rs.
    let c: &[(&str, f32)] = &[
        ("C_LOG2E", 1.442_695_f32),
        ("C_LN2_HI", 0.693_145_75_f32),
        ("C_LN2_LO", 1.428_606_8e-6_f32),
        ("C_P3", 0.166_666_67_f32),
        ("C_P4", 0.041_666_668_f32),
        ("C_P5", 0.008_333_334_f32),
        ("C_P6", 0.001_388_888_9_f32),
        ("C_EXP_FLOOR", -70.0_f32),
        ("C_EXP_LO", -80.0_f32),
        ("C_EXP_HI", 80.0_f32),
        ("C_NORM_EPS", 1e-6_f32),
        ("C_ADAM_ZERO", 1e-30_f32),
    ];
    let mut s = String::from("// Generated by build.rs: exact bit patterns of the core's f32 constants.\n");
    for (n, v) in c {
        s += &format!("#define {n} uintBitsToFloat(0x{:08X}u) // {v:e}\n", v.to_bits());
    }
    s
}

/// Fails the build if any float multiply, add or subtract in a bit-exact shader lacks the
/// NoContraction decoration: a driver could then fuse it into an FMA and change the bits.
fn check_no_contraction(glslc: &Path, out: &Path, shader_dir: &Path, src: &Path, stem: &str) {
    let asm = out.join(format!("{stem}.spvasm"));
    let status = Command::new(glslc)
        .args(["--target-env=vulkan1.2", "-O0", "-S", "-I"])
        .arg(out)
        .arg("-I")
        .arg(shader_dir)
        .arg("-o")
        .arg(&asm)
        .arg(src)
        .status()
        .expect("glslc");
    assert!(status.success(), "glslc -S failed on {}", src.display());
    let text = fs::read_to_string(&asm).unwrap();
    let mut protected = std::collections::HashSet::new();
    for line in text.lines() {
        let w: Vec<&str> = line.split_whitespace().collect();
        if w.len() >= 3 && w[0] == "OpDecorate" && w[2] == "NoContraction" {
            protected.insert(w[1].to_string());
        }
    }
    let float_ops = ["OpFMul", "OpFAdd", "OpFSub", "OpVectorTimesScalar", "OpDot", "OpMatrixTimesVector"];
    for line in text.lines() {
        let w: Vec<&str> = line.split_whitespace().collect();
        if w.len() >= 3 && w[1] == "=" && float_ops.contains(&w[2]) && !protected.contains(w[0]) {
            panic!("{stem}: `{}` has no NoContraction decoration (mark the variable `precise`)", line.trim());
        }
    }
}

fn main() {
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let shader_dir = Path::new("shaders");
    println!("cargo:rerun-if-changed=shaders");
    println!("cargo:rerun-if-env-changed=GLSLC");
    fs::write(out.join("consts.glsl"), consts_glsl()).unwrap();

    let glslc = find_glslc();
    let mut names: Vec<String> = Vec::new();
    let mut entries: Vec<PathBuf> = fs::read_dir(shader_dir).unwrap().flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.extension().and_then(|e| e.to_str()) != Some("comp") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", p.display());
        let stem = p.file_stem().unwrap().to_str().unwrap().to_string();
        let spv = out.join(format!("{stem}.spv"));
        // -O0: no SPIR-V-level optimisation; the driver's compiler optimises anyway, and this
        // keeps the instruction stream a literal transcription of the GLSL.
        let status = Command::new(&glslc)
            .args(["--target-env=vulkan1.2", "-O0", "-I"])
            .arg(&out)
            .arg("-I")
            .arg(shader_dir)
            .arg("-o")
            .arg(&spv)
            .arg(&p)
            .status()
            .unwrap_or_else(|e| panic!("cannot run glslc ({}): {e}; set GLSLC", glslc.display()));
        assert!(status.success(), "glslc failed on {}", p.display());
        if !stem.contains("fast") {
            check_no_contraction(&glslc, &out, shader_dir, &p, &stem);
        }
        names.push(stem);
    }
    let mut rs = String::from("// Generated by build.rs\n");
    for n in &names {
        rs += &format!(
            "pub const {}: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{n}.spv\"));\n",
            n.to_uppercase()
        );
    }
    fs::write(out.join("shaders.rs"), rs).unwrap();
}
